#!/usr/bin/env bash
# Copies the set-theoretic types of Guillaume Duboc's branch type-variables of
# https://github.com/gldubc/elixir into lib/vendor/: Module.Types.Descr with its type
# variables, tallying and recursive types. The modules are renamed ProcessTypes.Descr*,
# so that they do not clash with the compiler's own, each file receives a header that
# acknowledges its author, and the patches of scripts/descr_patches/ are applied.
#
#   scripts/vendor_descr.sh [COMMIT]
#
# Without COMMIT, the commit recorded in lib/vendor/COMMIT is fetched again.
set -euo pipefail

repo=gldubc/elixir
root=$(cd "$(dirname "$0")/.." && pwd)
dest=$root/lib/vendor
commit=${1:-$(cat "$dest/COMMIT")}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

header() {
  cat <<HEADER
#
# Acknowledgement. This file is copied from the branch type-variables of Guillaume
# Duboc's fork of Elixir, https://github.com/gldubc/elixir/tree/type-variables, at
# commit $commit.
# Module.Types.Descr is the type representation of the Elixir compiler (Apache-2.0,
# see the SPDX lines above); the recursive type descriptors, the type variables and
# the tallying algorithm of that branch, including the whole of descr_tally.ex and
# descr_polymorphic.ex, are the work of Guillaume Duboc.
#
# Changes made here: the modules Module.Types.Descr* are renamed ProcessTypes.Descr*,
# and the patches of scripts/descr_patches/ are applied (see lib/vendor/README.md).
# Do not edit this file by hand: regenerate it with scripts/vendor_descr.sh.
HEADER
}

for file in descr.ex descr_tally.ex descr_polymorphic.ex; do
  curl -fsSL "https://raw.githubusercontent.com/$repo/$commit/lib/elixir/lib/module/types/$file" \
    -o "$tmp/$file"

  sed 's/Module\.Types\.Descr/ProcessTypes.Descr/g' "$tmp/$file" > "$tmp/$file.renamed"

  # The acknowledgement goes right after the SPDX lines, which stay first.
  {
    sed -n '1,2p' "$tmp/$file.renamed"
    header
    sed '1,2d' "$tmp/$file.renamed"
  } > "$dest/$file"

  grep -q '^# SPDX-License-Identifier: Apache-2.0$' "$dest/$file" ||
    { echo "$file: unexpected license header" >&2; exit 1; }
done

shopt -s nullglob
for patch in "$root"/scripts/descr_patches/*.patch; do
  patch --forward --no-backup-if-mismatch -p1 -d "$root" < "$patch"
done

echo "$commit" > "$dest/COMMIT"
echo "lib/vendor: copied $repo at $commit"
